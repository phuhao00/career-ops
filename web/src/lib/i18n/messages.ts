export function interpolate(s: string, vars?: MsgVars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
}

export function translate(locale: string, key: MsgKey, fallback?: string, vars?: MsgVars): string {
  const id = normalizeLocale(locale);
  const s = MESSAGES[id]?.[key] ?? EN[key] ?? fallback ?? key;
  return interpolate(s, vars);
}

